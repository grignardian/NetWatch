#ifndef ALERT_MANAGER_H
#define ALERT_MANAGER_H

#include "event_monitor.h"
#include <string>
#include <vector>
#include <map>
#include <set>

// Severity levels for generated alerts
enum class AlertSeverity {
    INFO,       // Normal network events (e.g. standard outgoing connection)
    WARNING,    // Important events (e.g. new listening port opened)
    SUSPICIOUS  // Security-sensitive events (e.g. port listed in rules.conf)
};

// Represents a security alert generated by the rule engine
struct SecurityAlert {
    AlertSeverity severity;
    std::string timestamp;
    std::string ruleName;       // e.g. "UNEXPECTED_PORT", "NEW_LISTENER", "NEW_PROCESS"
    std::string message;        // Human-readable alert description
    ConnectionInfo socket;      // Associated socket details
};

// Rule definition for an unexpected or suspicious port
struct PortRule {
    int port;
    std::string description;
};

class AlertManager {
public:
    // Initializes the Alert Manager and loads rules from config/rules.conf
    explicit AlertManager(const std::string& configPath = "config/rules.conf");

    // Loads unexpected port rules from the configuration file
    bool loadRules(const std::string& configPath);

    // Evaluates a detected network event and returns any triggered security alerts
    std::vector<SecurityAlert> evaluateEvent(const NetworkEvent& event);

    // Prints a formatted security alert to the console
    static void printAlert(const SecurityAlert& alert);

    // Returns the current map of configured unexpected ports
    const std::map<int, std::string>& getSuspiciousPorts() const;

    // Adds a temporary or user-configured suspicious port
    void addSuspiciousPort(int port, const std::string& description);

private:
    std::string configFilePath;
    std::map<int, std::string> suspiciousPorts; // Port -> Description
    std::set<std::string> knownProcesses;       // Processes observed with network activity
};

#endif // ALERT_MANAGER_H
